def bullets(items, indent=12):
    """A bulleted list. Each item is a string or (string, [sub-items])."""
    flow = []
    for it in items:
        if isinstance(it, tuple):
            text, subs = it
            flow.append(ListItem([Paragraph(text, item),
                                  bullets(subs, indent)], leftIndent=indent))
        else:
            flow.append(ListItem(Paragraph(it, item), leftIndent=indent))
    return ListFlowable(flow, bulletType="bullet", start="•", leftIndent=indent,
                        bulletFontSize=SIZE - 1, bulletOffsetY=0)


